#!/usr/bin/env python3
"""Generate ``docs/api/index.md`` from ``langgoap.__all__``.

The public surface is whatever ``langgoap/__init__.py`` exports.  Its
``__all__`` list is organised by ``# Heading`` comments; this script turns
each heading into a section with an ``autosummary`` block, so the API
reference can never list fewer names than the package exports (issue #66).
``tests/test_docs_api_index.py`` fails when the committed page is stale.

Usage:
    python docs/generate_api_index.py          # rewrite docs/api/index.md
    python docs/generate_api_index.py --check  # exit 1 when it is stale
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

DOCS_DIR = Path(__file__).resolve().parent
INIT_FILE = DOCS_DIR.parent / "langgoap" / "__init__.py"
TARGET = DOCS_DIR / "api" / "index.md"

#: Names in ``__all__`` that autosummary cannot document usefully.
SKIP = frozenset({"__version__"})

HEADER = """# API Reference

Every symbol below is re-exported from the top-level `langgoap` package
(`langgoap.__all__`) and is the supported public surface. Anything **not**
listed here is internal and may change without notice. `langgoap.__version__`
is the installed version string.

This page is generated by `docs/generate_api_index.py` from the grouping
comments in `langgoap/__init__.py`; `tests/test_docs_api_index.py` fails
when the two drift apart.
"""

FOOTER = """
```{toctree}
:maxdepth: 2
:hidden:
```
"""


def parse_groups(source: str) -> list[tuple[str, list[str]]]:
    """Return ``[(heading, [names])]`` in ``__all__`` order.

    Names that precede the first ``# Heading`` comment fall under
    ``"Package"``.
    """
    match = re.search(r"^__all__\s*=\s*\[\n(.*?)^\]", source, re.S | re.M)
    if match is None:
        raise SystemExit(f"no __all__ list found in {INIT_FILE}")
    groups: list[tuple[str, list[str]]] = []
    title = "Package"
    names: list[str] = []
    for raw in match.group(1).splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("#"):
            if names:
                groups.append((title, names))
                names = []
            title = line.lstrip("#").strip()
            continue
        entry = re.fullmatch(r'"([A-Za-z_][A-Za-z0-9_]*)",?', line)
        if entry and entry.group(1) not in SKIP:
            names.append(entry.group(1))
    if names:
        groups.append((title, names))
    return groups


def is_constant(name: str) -> bool:
    """``UPPER_CASE`` exports are instances, not classes or functions."""
    return name.upper() == name


def constant_type(name: str) -> str:
    """The type name of the exported constant ``langgoap.<name>``."""
    import langgoap

    return type(getattr(langgoap, name)).__name__


def render(groups: list[tuple[str, list[str]]]) -> str:
    """Render the Markdown page for ``groups``.

    Classes and functions go through ``autosummary``.  Constants are listed
    as bullets with their type: an ``autodata`` stub for an instance such
    as ``FIRE_ONCE`` repeats its class's attribute descriptions and Sphinx
    reports every one of them as a duplicate.
    """
    parts = [HEADER]
    for title, names in groups:
        summarised = [n for n in names if not is_constant(n)]
        constants = [n for n in names if is_constant(n)]
        parts.append(f"\n## {title}\n")
        if summarised:
            parts.append(
                "\n```{eval-rst}\n.. autosummary::\n"
                "   :toctree: generated\n   :nosignatures:\n\n"
            )
            parts.extend(f"   langgoap.{name}\n" for name in summarised)
            parts.append("```\n")
        if constants:
            parts.append("\nConstants:\n\n")
            parts.extend(
                f"- `langgoap.{name}` (`{constant_type(name)}`)\n" for name in constants
            )
    parts.append(FOOTER)
    return "".join(parts)


def main(argv: list[str]) -> int:
    content = render(parse_groups(INIT_FILE.read_text()))
    if "--check" in argv:
        if TARGET.read_text() != content:
            print(
                f"{TARGET} is stale; run python {Path(__file__).name}", file=sys.stderr
            )
            return 1
        return 0
    TARGET.write_text(content)
    print(f"wrote {TARGET.relative_to(DOCS_DIR.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
